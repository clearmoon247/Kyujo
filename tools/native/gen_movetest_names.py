"""Writes movetest_names.c: the species and move names the "Move animation test" page lists (src/platform/host_movetest.c).

    gen_movetest_names.py <patched decomp tree> <output .c file>

The names are read from the decomp being built (include/pokemon.h: `#define BULBASAUR 1` ... `MEW 151`; include/moves.h: `#define POUND 0x01`
... `STRUGGLE 0xA5`), turned into display form ("MR_MIME" -> "Mr Mime") and written into a generated file in the build folder. Nothing from the
decomp is stored in this repository. Standard library only."""
import re
import sys


# Names that a plain "capitalise each word" gets wrong (the decomp's identifiers avoid punctuation and clashes with its own macros).
SPECIAL = {"FARFETCH_D": "Farfetch'd", "NIDORAN_F": "Nidoran (F)", "NIDORAN_M": "Nidoran (M)", "MR_MIME": "Mr. Mime", "PSYCHIC_M": "Psychic"}


def display(name):
    if name in SPECIAL:
        return SPECIAL[name]
    return " ".join(w.capitalize() for w in name.split("_"))


def read_defines(path, first_stop):
    """(name, value) for the `#define NAME VALUE` lines of the file up to the first line whose name starts with `first_stop`."""
    out = []
    for line in open(path, encoding="utf-8", errors="replace"):
        m = re.match(r"#define\s+([A-Z][A-Z0-9_]*)\s+(0x[0-9A-Fa-f]+|\d+)\b", line)
        if not m:
            continue
        if m.group(1).startswith(first_stop):
            break
        out.append((m.group(1), int(m.group(2), 0)))
    return out


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    tree, out_path = sys.argv[1], sys.argv[2]
    species = [(n, v) for n, v in read_defines(tree + "/include/pokemon.h", "RGBY_") if 1 <= v <= 151]
    moves = [(n, v) for n, v in read_defines(tree + "/include/moves.h", "ABC_") if 1 <= v <= 0xA5]
    if len(species) != 151 or len(moves) != 165:
        sys.exit("expected 151 species and 165 moves, found %d and %d: the decomp's header layout is not what this script expects" % (len(species), len(moves)))
    table = lambda items, size: [""] * size
    sp, mv = table(species, 152), table(moves, 166)
    for n, v in species:
        sp[v] = display(n)
    for n, v in moves:
        mv[v] = display(n)
    with open(out_path, "w") as f:
        f.write("/* Generated by tools/native/gen_movetest_names.py from the decomp being built. Not part of the repository. */\n")
        f.write("const char *const gMoveTestSpeciesName[152] = {\n")
        f.write("".join('    "%s",\n' % s for s in sp))
        f.write("};\nconst char *const gMoveTestMoveName[166] = {\n")
        f.write("".join('    "%s",\n' % s for s in mv))
        f.write("};\n")
    print("movetest names: %d species, %d moves -> %s" % (len(species), len(moves), out_path))


if __name__ == "__main__":
    main()
