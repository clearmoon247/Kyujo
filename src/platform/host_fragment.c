/*
 * host_fragment.c - turns "a call into a loaded code overlay" into a call of the native function that stands for it.
 *
 * Background. The console's game is split into a main program and 77 code overlays ("fragments", src/fragments/*). The game loads a
 * fragment from the ROM into its memory pool (Fragment_Load, src/jpeg_stream.c), patches ("relocates") the addresses inside it
 * (Memmap_RelocateFragment, src/memmap.c) and then jumps to its start. In this port every fragment's C code is compiled and linked into
 * the program, so the copy in the pool is never executed; what the game does with the pool pointer is call it.
 *
 * tools/native/be_memory.py therefore sends the target of EVERY indirect call of game code through HostResolveCallTarget (below). If the
 * target lies inside a fragment that has been loaded, it is converted to the address the console had linked that code at and looked up
 * in the table generated by tools/native/gen_platform_symbols.py (gen/fragment_table.c). Everything else passes through unchanged.
 * A call into the pool that nothing explains stops the program with a message, never jumps blindly.
 *
 * Which fragment is where: the loader reports every fragment it relocates (port patch 0011 -> HostNoteFragmentLoaded below), and this file
 * keeps the list of extents itself. The game's own table (gFragments, src/memmap.c) is not used for this because it holds one entry per
 * fragment id and a later load with the same id replaces the entry, while the earlier code stays in the pool and stays callable.
 *
 * Jumps in the image (the fragment header and hand-written jump tables) are followed to their destination; see below.
 *
 * Code that no table entry explains (raw binary fragments) goes to host_mips_stub.c.
 *
 * The fragments' DATA is the program's own static data, not the copy loaded into the pool. The console reloads an overlay's data from
 * the ROM at every load, so every visit to a screen starts from scratch; natively the variables would keep what the last visit left.
 * To get the same behaviour, be_memory.py puts each overlay's writable variables into two sections of their own (initialised /
 * zero-filled), gen/fragment_data.c says where they are, host_fragments_snapshot() copies the initialised ones once at start-up (after the
 * big-endian reversal) and HostNoteFragmentLoaded restores both sections whenever the overlay is loaded.
 *
 * Known limits, kept visible:
 *   - a second load of an overlay that is still loaded (two live copies) would reset the variables the first copy is using; the
 *     console would have kept two separate sets. Not seen so far;
 *   - variables that are not in a fragment's own source files (shared with the main program) are not reset;
 *   - two unused fragments (51 and 52) share one overlay address, so a call into either of them would be ambiguous.
 *
 * HOST-side file (plain C types only; it calls one game function through its plain-integer signature).
 */
#include <stdio.h>
#include <stdlib.h>

#include "platform.h"

/* Generated: gen/fragment_table.c. Sorted by overlay address. */
struct HostFragmentFunc {
    unsigned int overlay_addr;
    void (*fn)(void);
};
extern const struct HostFragmentFunc gHostFragmentFuncs[];
extern const unsigned int gHostFragmentFuncCount;
extern const unsigned int gHostPoolBytes;

extern unsigned char gPool[];                                   /* the game's memory pool (src/heap.c) */

/* Generated: gen/fragment_data.c. Where each overlay's variables are. */
struct HostFragmentData {
    unsigned int base;
    const char *name;
    unsigned char *data_start, *data_end, *zero_start, *zero_end;
};
extern const struct HostFragmentData gHostFragmentData[];
extern const unsigned int gHostFragmentDataCount;

static unsigned char *sFragmentDataSnapshot[512];             /* per entry of gHostFragmentData: a copy of the initialised variables */

/* Copies every overlay's initialised variables, once, after the start-up reversal of big-endian data and before the game runs. */
void host_fragments_snapshot(void)
{
    unsigned int i;
    if (gHostFragmentDataCount > 512) host_fatal("more than 512 overlays with variables (raise the size in host_fragment.c)");
    for (i = 0; i < gHostFragmentDataCount; i++) {
        const struct HostFragmentData *d = &gHostFragmentData[i];
        unsigned long n = (unsigned long)(d->data_end - d->data_start);
        if (d->data_start == 0 || n == 0) continue;
        sFragmentDataSnapshot[i] = (unsigned char *)malloc(n);
        if (!sFragmentDataSnapshot[i]) host_fatal("out of memory saving the overlays' start-up variables");
        {   unsigned long k; for (k = 0; k < n; k++) sFragmentDataSnapshot[i][k] = d->data_start[k]; }
    }
}

/* Puts the variables of the overlay(s) linked at `base` back to their start-up state (the console's loader did this by copying the data
 * from the ROM and clearing the zero-filled part). Does nothing for an overlay that has no variables of its own. */
static void reset_fragment_variables(unsigned int base)
{
    unsigned int i;
    for (i = 0; i < gHostFragmentDataCount; i++) {
        const struct HostFragmentData *d = &gHostFragmentData[i];
        unsigned long k, n;
        if (d->base != base) continue;
        if (sFragmentDataSnapshot[i]) {
            n = (unsigned long)(d->data_end - d->data_start);
            for (k = 0; k < n; k++) d->data_start[k] = sFragmentDataSnapshot[i][k];
        }
        if (d->zero_start) {
            n = (unsigned long)(d->zero_end - d->zero_start);
            for (k = 0; k < n; k++) d->zero_start[k] = 0;
        }
        /* no return: several overlays can share one slot (one base address); the one being loaded replaces the others' memory on the console,
         * so all of them start from scratch (the others are not in use any more, or their next load would reset them anyway) */
    }
}

/* The fragments that have been relocated into the pool, newest last. A new fragment removes the entries it overlaps (the memory is
 * theirs no more). `base` is the address the console's linker gave the fragment: 0x80000000 | ((id + 0x10) << 20), the same formula as
 * Memmap_GetLoadedFragmentVaddr in src/memmap.c. */
#define MAX_EXTENTS 512
struct Extent {
    unsigned int start, size, base;
};
static struct Extent sExtents[MAX_EXTENTS];
static unsigned int sExtentCount;

/* Called by the game's Memmap_RelocateFragment (port patch 0011). */
void HostNoteFragmentLoaded(unsigned int id, void *fragment, unsigned int size)
{
    unsigned int start = (unsigned int)(unsigned long)fragment, i, kept = 0;

    for (i = 0; i < sExtentCount; i++) {                         /* drop what the new fragment overwrites */
        if (sExtents[i].start + sExtents[i].size <= start || start + size <= sExtents[i].start) {
            sExtents[kept++] = sExtents[i];
        }
    }
    sExtentCount = kept;
    if (sExtentCount == MAX_EXTENTS) {
        host_fatal("more than 512 fragments are loaded at once (raise MAX_EXTENTS in host_fragment.c)");
    }
    sExtents[sExtentCount].start = start;
    sExtents[sExtentCount].size = size;
    sExtents[sExtentCount].base = 0x80000000u | ((id + 0x10u) << 20);
    reset_fragment_variables(sExtents[sExtentCount].base);        /* a fresh load starts from the overlay's initial data, like on the console */
    sExtentCount++;
}

/* The overlay address of a pool address inside a loaded fragment, or 0. */
static unsigned int overlay_of(unsigned int addr)
{
    unsigned int i;
    for (i = sExtentCount; i-- > 0;) {                           /* newest first */
        if (addr >= sExtents[i].start && addr - sExtents[i].start < sExtents[i].size) {
            return sExtents[i].base + (addr - sExtents[i].start);
        }
    }
    return 0;
}

/* Binary search in the generated table; NULL if the overlay address is not a known function. */
static void *lookup(unsigned int overlay)
{
    unsigned int lo = 0, hi = gHostFragmentFuncCount;            /* search in [lo, hi) */
    while (lo < hi) {
        unsigned int mid = lo + (hi - lo) / 2;
        if (gHostFragmentFuncs[mid].overlay_addr < overlay) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    if (lo == gHostFragmentFuncCount || gHostFragmentFuncs[lo].overlay_addr != overlay) {
        return NULL;
    }
    return (void *)gHostFragmentFuncs[lo].fn;
}

/* The pool address of code that the console linked at `link_addr` (0x81xxxxxx style), in the newest loaded fragment whose link range holds
 * it, or 0 if no loaded fragment does. Used by the machine-code interpreter (host_mips.c) to enter hand-written assembly by its symbol
 * address. */
unsigned int host_fragment_pool_addr(unsigned int link_addr)
{
    unsigned int i;
    for (i = sExtentCount; i-- > 0;) {
        if (link_addr >= sExtents[i].base && link_addr - sExtents[i].base < sExtents[i].size) {
            return sExtents[i].start + (link_addr - sExtents[i].base);
        }
    }
    return 0;
}

/* The address the console linked the loaded fragment byte at `pool_addr` at (0x81xxxxxx style), or 0 if it is in no loaded fragment.
 * For messages: the decomp's symbol lists and the disassembly use these addresses. */
unsigned int host_fragment_link_addr(unsigned int pool_addr)
{
    return overlay_of(pool_addr);
}

/* If `pool_addr` is code that this port has as a native function (a fragment's C code), returns that function; otherwise NULL (hand-written
 * assembly in the image, or an address that is not in a loaded fragment). Never stops the program. */
void *host_fragment_native(unsigned int pool_addr)
{
    unsigned int overlay;
    if (pool_addr < (unsigned int)(unsigned long)gPool || pool_addr - (unsigned int)(unsigned long)gPool >= gHostPoolBytes) return NULL;
    overlay = overlay_of(pool_addr);
    return overlay ? lookup(overlay) : NULL;
}

void *HostResolveCallTarget(void *target)
{
    unsigned int addr = (unsigned int)(unsigned long)target;
    unsigned int overlay;
    void *fn;

    if (addr < (unsigned int)(unsigned long)gPool || addr - (unsigned int)(unsigned long)gPool >= gHostPoolBytes) {
        return target;                                           /* the common case: not in the pool */
    }
    overlay = overlay_of(addr);
    if (overlay == 0) {
        fprintf(stderr, "kyujo: a call goes to 0x%08X inside the memory pool, but no fragment is loaded there\n", addr);
        host_fatal("indirect call into the memory pool outside any loaded fragment");
    }
    fn = lookup(overlay);
    if (fn == NULL) {
        /* Not a function the port knows by address. Two things in a fragment's image are jumps rather than functions: its header
         * (struct Fragment, src/memmap.h: "j <main function>; nop") and hand-written jump tables ("j <function>; nop" entries, e.g. the
         * table at the start of the particle data library, ROM 0x2552E0). In both the target is the destination of the jump. MIPS `j`
         * keeps the top 4 bits of the address of the instruction after it and replaces the lower 28 bits by (26-bit field << 2). Game memory
         * is big-endian. The second word must be 0 (a `nop` in the delay slot) so that data is not mistaken for a jump. */
        const unsigned char *b = (const unsigned char *)target;
        unsigned int inst = ((unsigned int)b[0] << 24) | ((unsigned int)b[1] << 16) | ((unsigned int)b[2] << 8) | b[3];
        unsigned int delay = ((unsigned int)b[4] << 24) | ((unsigned int)b[5] << 16) | ((unsigned int)b[6] << 8) | b[7];
        if ((inst >> 26) == 2 && delay == 0) {
            unsigned int dest = ((addr + 4) & 0xF0000000u) | ((inst & 0x03FFFFFFu) << 2);
            if (dest >= (unsigned int)(unsigned long)gPool && dest - (unsigned int)(unsigned long)gPool < gHostPoolBytes) {
                return HostResolveCallTarget((void *)(unsigned long)dest);       /* the loader relocated the jump into the pool */
            }
            fn = lookup(0x80000000u | (dest & 0x0FFFFFFFu));                      /* a jump the loader could not relocate: the target
                                                                                     fragment is not loaded; use the linked-in function */
        }
    }
    if (fn == NULL) {
        /* Last resort: code in a fragment that has no C source at all (a raw binary file such as a model archive; its entry is a few
         * instructions made by the original build tools). It is executed by the strict interpreter in host_mips_stub.c, which stops the
         * program with a message on anything it does not understand. */
        return host_mips_thunk(addr);
    }
    return fn;
}
