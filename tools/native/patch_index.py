"""Writes docs/port-patches.md: the list of port patches with each patch's own explanation.

The text comes from the head of every port/patches/*.patch file (everything before the first `--- a/` line), so the document cannot drift
from the patches. Run it after adding or changing a patch:   python3 tools/native/patch_index.py
Standard library only."""
import glob
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))


def main():
    out = ["# Port patches\n",
           "Generated by `tools/native/patch_index.py` from the heads of `port/patches/*.patch`; edit the patch head, not this file.\n",
           "The decomp itself is never modified: `tools/native/srctree.py` copies it and applies these patches in order, and the native build "
           "compiles the copy. Each patch states what it changes and WHY.\n"]
    for path in sorted(glob.glob(os.path.join(REPO, "port", "patches", "*.patch"))):
        text = open(path).read()
        head = text.split("\n--- a/", 1)[0].strip("\n")
        files = [l[6:].strip() for l in text.splitlines() if l.startswith("+++ b/")]
        name = os.path.basename(path)
        out.append("\n## %s\n" % name)
        out.append(head + "\n")
        out.append("Files: " + ", ".join("`%s`" % f for f in files) + "\n")
    with open(os.path.join(REPO, "docs", "port-patches.md"), "w") as f:
        f.write("\n".join(out))
    print("wrote docs/port-patches.md")


if __name__ == "__main__":
    main()
